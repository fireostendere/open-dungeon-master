const serverUrl = process.argv[2] || "http://api.iroslyakov.com:3005";
const token = process.env.ODM_MCP_TOKEN || process.argv[3];
if (!token) throw new Error("Set ODM_MCP_TOKEN or pass token as argument 3.");

console.log(`Creating Ignat for odm_admin, White_Goose, and shigaevaler at ${serverUrl}...`);

for (const username of ["odm_admin", "White_Goose", "shigaevaler"]) {
  const userPayload = JSON.parse(JSON.stringify(payload));
  userPayload.params.owner = { username };

  const res = await fetch(`${serverUrl}/api/internal/mcp`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify(userPayload),
  });

  const data = await res.json();
  if (data.ok) {
    console.log(`[SUCCESS] Created Ignat for ${username}: ${data.result.character.id}`);
  } else {
    console.error(`[ERROR] Failed for ${username}:`, data.error);
  }
}
