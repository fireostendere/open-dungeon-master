// Actual ODM DM client and dice engine against the isolated CI app server.
import assert from 'node:assert/strict';
import {register} from 'node:module';
register('../lib/register-alias.mjs',import.meta.url);
const {getGlobalConfig}=await import('../../src/lib/db/app-settings.ts');
const {requestDmMessage}=await import('../../src/lib/dm/model.ts');
const {rollExpression}=await import('../../src/lib/dice.ts');
const config=getGlobalConfig().text;
assert.match(config.customBaseUrl,/api\/internal\/codex\/v1\/chat\/completions$/);
const settings={textProvider:'custom',localTextModel:'',customBaseUrl:config.customBaseUrl,customModel:config.customModel,customApiKey:config.customApiKey};
const messages=[{role:'system',content:'Игровые числа вычисляет движок. Используй roll_dice.'},{role:'user',content:'Брось d20.'}];
const tools=[{type:'function',function:{name:'roll_dice',description:'Game dice',parameters:{type:'object',properties:{sides:{type:'integer'}},required:['sides']}}}];
const first=await requestDmMessage(settings,messages,{tools,toolChoice:'auto'});
if(first.error)throw new Error(await first.error.text());
const call=first.message.tool_calls[0];assert.equal(call.function.name,'roll_dice');
const rolled=rollExpression('1d20');assert.ok(rolled.total>=1&&rolled.total<=20);
const second=await requestDmMessage(settings,[...messages,{role:'assistant',content:'',tool_calls:[call]},{role:'tool',tool_call_id:call.id,content:JSON.stringify({total:rolled.total})}],{tools,toolChoice:'none'});
if(second.error)throw new Error(await second.error.text());
assert.ok(second.message.content.includes(String(rolled.total)));
console.log('PASS actual requestDmMessage -> requestCustomMessage -> HTTP bridge -> native tool -> real ODM dice -> final reply.');
